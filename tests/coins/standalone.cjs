const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=require('../../tools/read-test-html.cjs')();
const source=html.match(/<script id="game-coins-v2">([\s\S]*?)<\/script>/)[1];
const ctx={window:{},state:{objects:[]}};vm.createContext(ctx);
vm.runInContext(source.slice(0,source.indexOf('  let records='))+'})();',ctx);
const calc=ctx.window.__gameCoinsCore.calculate;
const log={shiftId:'s',truckId:'t',timestamp:10,createdByEmail:'operator@example.com',createdBy:'Operator',clientOperationId:'op1'};
const history=(id,timestamp,operations)=>({id,timestamp,userEmail:'operator@example.com',userName:'Operator',eventType:'history',history:{operations,undone:false}});
const load=history('load',10,[{collection:'logs',id:'l',before:null,after:log}]);
const arrival=history('arrival',20,[{collection:'truckStatus',id:'t',before:{shiftId:'s',lastLoadTimestamp:10},after:{shiftId:'s',lastLoadTimestamp:10,arriveTimestamp:20}}]);
const archive=history('archive',30,[{collection:'archive',id:'a',before:null,after:{sourceShiftId:'s',logs:[{id:'l',...log}]}}]);
const cleanup=history('cleanup',40,[{collection:'logs',id:'l',before:log,after:null}]);
const coins=rows=>calc(rows).reduce((n,r)=>n+r.coins,0);
assert.equal(coins([load,arrival]),3);
assert.equal(coins([load,arrival,archive,cleanup]),3,'Closing an archived shift must preserve earnings');
assert.equal(coins([load,arrival,cleanup]),2,'An actual deleted trip must reverse its reward');
assert.equal(coins([load,load,arrival,archive,cleanup]),3,'Duplicate delivery must not double rewards');
assert.equal(calc([load,arrival,archive,cleanup]).movements.reduce((n,r)=>n+r.amount,0),3);
const wrongArchive=JSON.parse(JSON.stringify(archive));wrongArchive.history.operations[0].after.logs[0].timestamp=999;
assert.equal(coins([load,arrival,wrongArchive,cleanup]),2,'Unrelated archive data must not protect a cancellation');
const paid=JSON.parse(JSON.stringify(load));paid.history.gameRewards={version:1,load:5,arrive:7,ttn:3};
assert.equal(coins([paid]),5);
const adminLoad=JSON.parse(JSON.stringify(load));adminLoad.userEmail='admin@example.com';adminLoad.history.operations[0].after.createdByEmail='admin@example.com';
assert.equal(coins([adminLoad]),1,'Roles use the same accrual rate');
console.log('PASS exact standalone coin calculator: operator, administrator, policy, archival cleanup, cancellation, deduplication, ledger totals');

const shop=html.match(/<script id="road-shop-v1">([\s\S]*?)<\/script>/)[1];
const available=shop.match(/const available=(.*);/)[1];
const cash={window:{},currentUid:'operator',bonus:()=>0,adjustments:()=>0,snapshot:()=>({adjustments:[]})};
vm.createContext(cash);vm.runInContext('available='+available,cash);
assert.equal(cash.available(-3,0,'lopater','active'),-3);
assert.equal(cash.available(10,25,'lopater','active'),-15);
assert.equal(cash.available(30,25,'lopater','active'),5);
console.log('PASS signed wallet balance: penalties and spending retain negative amounts');
